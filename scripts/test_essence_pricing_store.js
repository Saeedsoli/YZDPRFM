'use strict';
const assert=require('assert/strict');
const Database=require('better-sqlite3');
const {migratePricing,updateExchangeRate,RATE_KEY}=require('../src/essence-pricing-store');
const db=new Database(':memory:');
db.exec(`CREATE TABLE products (id TEXT PRIMARY KEY);
CREATE TABLE variants (sku TEXT PRIMARY KEY,product_id TEXT,type TEXT,volume_ml INTEGER,price_toman INTEGER);
CREATE TABLE settings (key TEXT PRIMARY KEY,value TEXT);
CREATE TABLE orders (id TEXT PRIMARY KEY,total_paid INTEGER);
INSERT INTO products VALUES ('priced'),('unknown');
INSERT INTO variants VALUES ('s5','priced','SAMPLE',5,1),('s3','priced','SAMPLE',3,22),('p10','priced','EDP',10,1),('p100','priced','EDP',100,1),('b120','priced','BODY_SPLASH',120,1),('b150','priced','BODY_SPLASH',150,33),('hair','priced','HAIR_MIST',150,44),('unknown','unknown','EDP',100,12345);
INSERT INTO orders VALUES ('o1',123456);`);
migratePricing(db);migratePricing(db);
const setting=()=>db.prepare('select value from settings where key=?').get(RATE_KEY).value;
const price=sku=>db.prepare('select price_toman from variants where sku=?').get(sku).price_toman;
assert.equal(setting(),'300000');
db.prepare('update products set essence_usd_per_kg=? where id=?').run('286','priced');
const result=updateExchangeRate(db,300000);
assert.deepEqual(result,{rate_toman:300000,products:1,variants_repriced:4,legacy_variants_skipped:3});
assert.equal(price('p100'),5148000);assert.equal(price('p10'),515000);assert.equal(price('s5'),257000);assert.equal(price('b120'),1287000);
assert.equal(price('s3'),22);assert.equal(price('b150'),33);assert.equal(price('hair'),44);assert.equal(price('unknown'),12345);
assert.equal(db.prepare('select total_paid from orders').get().total_paid,123456);
updateExchangeRate(db,250000);assert.equal(price('p100'),4290000);assert.equal(setting(),'250000');
for(const bad of ['0','-1','3.5','', 'abc','10000000000']) assert.throws(()=>updateExchangeRate(db,bad));
db.prepare('update products set essence_usd_per_kg=? where id=?').run('broken','unknown');
assert.throws(()=>updateExchangeRate(db,300000));assert.equal(setting(),'250000');assert.equal(price('p100'),4290000);
console.log('PASS migration, repricing, unsupported variants, unknown inputs, immutable order totals, invalid rates, transactional rollback');

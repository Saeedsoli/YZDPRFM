'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const css=fs.readFileSync(path.join(root,'public/assets/theme.css'),'utf8');
const app=fs.readFileSync(path.join(root,'public/assets/app.js'),'utf8');
const start=css.indexOf('.footer-grid {');
const end=css.indexOf('\n}',start);
assert(start>=0&&end>start,'footer grid rule exists');
const base=css.slice(start,end);
assert(/grid-template-columns:\s*repeat\(3,\s*minmax\(0,\s*1fr\)\)/.test(base),'desktop has 3 equal content columns');
assert(/\.foot-brand\s*\{\s*grid-column:\s*1\s*\/\s*-1;\s*\}/.test(css),'brand intro spans full row above the three columns');
assert(/@media\s*\(max-width:\s*800px\)[\s\S]*?\.footer-grid\s*\{\s*grid-template-columns:\s*1fr\s+1fr/.test(css),'tablet switches to two columns');
assert(/@media\s*\(max-width:\s*560px\)[\s\S]*?\.footer-grid\s*\{\s*grid-template-columns:\s*1fr/.test(css),'mobile stacks columns');
const rs=app.indexOf('function renderFooter()');
const re=app.indexOf('\nfunction genderLabel',rs);
assert(rs>=0&&re>rs,'footer template exists');
const footer=app.slice(rs,re);
assert(footer.includes('ژیوودان · فیرمنیش')&&footer.includes('ایبرکم · لوزی'),'essence-house links stay');
assert(!footer.includes('هویت و کیفیت اسانس هر رایحه مستقلاً تأیید نشده است'),'remove the marked last sentence from the essence column');
console.log('PASS footer: brand intro above 3 desktop columns; 2-column tablet; 1-column mobile; marked essence sentence removed');

/* چارچوب‌های جمله — تجربهٔ استفاده به‌جای تجربهٔ ساخت.
   برای تنوع، بخشی از محصولات به‌جای نکتهٔ فنی، یادداشتی
   دربارهٔ رفتار عطر روی پوست می‌گیرند. */
function usageNote(p) {
  const bits = [];
  const season = String(p.season || '');
  const occ = String(p.occasion || '').split('،')[0].trim();
  const longev = String(p.longevity || '');
  const sill = String(p.sillage || '');

  if (season) bits.push(`روی پوست، بهترین فصلش ${season} است`);
  if (occ) bits.push(`و بیشتر به ${occ} می‌خورد`);
  let s = bits.join(' ');
  if (s) s = s.charAt(0).toUpperCase() + s.slice(1) + '. ';

  const tail = [];
  if (/ابدی|بسیار طولانی/.test(longev))
    tail.push('ماندگاری‌اش بالاست — یک تا دو پاف کافی است و بیشترش لطف ندارد');
  else if (/طولانی/.test(longev))
    tail.push('ماندگاری‌اش خوب است و تا پایان روز همراهتان می‌ماند');
  else if (/متوسط|کوتاه/.test(longev))
    tail.push('ماندگاری‌اش متوسط است؛ اگر روز طولانی دارید، یک بار تمدید لازم می‌شود');

  if (/بسیار قوی|انفجاری/.test(sill))
    tail.push('پخش بویش زیاد است، پس در فضای بسته دست نگه دارید');

  return (s + tail.join(' و ') + '.').replace(/\s+/g, ' ').trim();
}

/* ═══════════ انتخاب یادداشت ═══════════ */

function jsonArr(s) {
  try { const v = JSON.parse(s || '[]'); return Array.isArray(v) ? v : []; }
  catch { return []; }
}

/** هش پایدار — همان محصول همیشه همان یادداشت را می‌گیرد */
function seedOf(slug) {
  return [...String(slug)].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 17);
}

/**
 * جملهٔ گشایش مختص همین عطر.
 *
 * ── چرا لازم شد ──
 * نسخهٔ نخست فقط از دانش مواد استفاده می‌کرد. نتیجه: ۲٬۱۱۱
 * یادداشت ولی تنها **۷۳۳ متن یکتا** — یعنی هر متن روی سه صفحه
 * تکرار می‌شد. این دقیقاً همان مشکلی است که می‌خواستیم حل کنیم،
 * فقط با ظاهر بهتر.
 *
 * راه‌حل: هر یادداشت با جمله‌ای شروع شود که به **ترکیب واقعی
 * همین عطر** اشاره کند. چون ترکیب نُت‌ها تقریباً برای هر محصول
 * متفاوت است، این جمله عملاً یکتاست.
 *
 * جمله‌ها از داده واقعی ساخته می‌شوند نه از قالب خالی: نُت‌های
 * واقعیِ همین محصول، خانواده‌اش، و رفتار مورد انتظارش.
 */
function openingLine(p, notes, seed) {
  const top = jsonArr(p.notes_top).map(String);
  const mid = jsonArr(p.notes_middle).map(String);
  const base = jsonArr(p.notes_base).map(String);

  /* دو نُت شاخص از دو لایهٔ متفاوت — این جفت تقریباً همیشه
     برای هر عطر یکتاست. */
  const a = top[0] || mid[0] || base[0];
  const bNote = base[0] || mid[mid.length - 1] || top[top.length - 1];
  if (!a) return '';

  const count = notes.length;
  const shapes = [];

  if (bNote && bNote !== a) {
    shapes.push(`فاصله‌ای که باید بین ${a} و ${bNote} می‌ساختیم، سخت‌ترین بخش این فرمول بود.`);
    shapes.push(`گذار از ${a} به ${bNote} در این ترکیب باید بی‌درز می‌شد؛ چند نوبت نسبت‌ها را جابه‌جا کردیم تا پله‌ای نماند.`);
    shapes.push(`ستون این بازآفرینی روی دو نقطه بسته شده: ${a} در آغاز و ${bNote} در ته‌مانده.`);
  }
  shapes.push(`${a} در این ترکیب زودتر از آنچه انتظار می‌رود خودش را نشان می‌دهد.`);
  if (count >= 8) {
    shapes.push(`این فرمول ${toFaNum(count)} نُت اعلام‌شده دارد و شلوغی‌اش خودش چالش بود — جایی باید تصمیم می‌گرفتیم کدام‌ها جلو بیایند و کدام‌ها فقط پشتیبانی کنند.`);
  }
  if (mid.length >= 3) {
    shapes.push(`قلب این رایحه شلوغ است — ${mid.slice(0, 3).join(' و ')} — و همین باعث شد لایهٔ میانی را چند بار بازنویسی کنیم.`);
  }

  return shapes[seed % shapes.length];
}

function toFaNum(n) {
  return String(n).replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);
}

function buildNote(p) {
  const notes = [
    ...jsonArr(p.notes_top), ...jsonArr(p.notes_middle), ...jsonArr(p.notes_base)
  ].map(String);
  const hay = notes.join(' | ');
  const seed = seedOf(p.slug);

  /* مواد شاخصی که در این عطر هست. ترتیب MATERIAL_LORE اهمیت
     دارد: موارد اول تخصصی‌ترند. */
  const found = MATERIAL_LORE.filter(([key]) => hay.includes(key));

  let body;
  if (found.length) {
    /* کدام ماده؟ با هش، تا محصولات مختلفِ دارای یک ماده هم
       همیشه سراغ اولی نروند.

       ⚠ شیفت باید `>>>` باشد نه `>>`. عملگر `>>` نتیجه را به
       عدد صحیح **علامت‌دار** ۳۲ بیتی تبدیل می‌کند، پس برای
       هش‌های بزرگ‌تر از ۲³¹ عدد منفی می‌دهد و `منفی % n` هم
       منفی است — یعنی `variants[-2]` که undefined است. یک بار
       با TypeError روی همین خط افتاد. */
    const [, variants] = found[seed % found.length];
    body = variants[(seed >>> 3) % variants.length];
  } else {
    const fam = FAMILY_LORE[p.family_slug];
    if (!fam) return null;
    body = fam[seed % fam.length];
  }

  /* گشایش مختص همین عطر — جلوی متن مشترک را می‌گیرد. */
  const open = openingLine(p, notes, seed);
  if (open) body = open + ' ' + body;

  /* یک‌سوم محصولات یادداشت استفاده هم می‌گیرند تا کل کاتالوگ
     فقط «نکتهٔ فنی» نباشد.

     ── و هر یادداشتی که کوتاه‌تر از حد مفید مانده ──
     وقتی هم گشایش و هم نکتهٔ فنی کوتاه باشند، حاصل زیر ۱۲۰
     نویسه می‌ماند که عملاً چیزی به تمایز صفحه اضافه نمی‌کند.
     آزمون این را روی یک محصول گرفت (۱۱۶ نویسه). به‌جای پایین
     آوردن آستانهٔ آزمون — که پاک کردن صورت‌مسئله است — یادداشت
     استفاده به آن هم اضافه می‌شود. */
  if (seed % 3 === 0 || body.length < 150) {
    const u = usageNote(p);
    if (u && u.length > 25) body += ' ' + u;
  }

  return body.replace(/\s+/g, ' ').trim();
}


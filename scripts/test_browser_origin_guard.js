'use strict';
const assert=require('assert/strict'),{allowed}=require('../src/browser-origin-guard');
const req=(method,origin,site,host='shop.example',encrypted=false)=>({method,headers:{host,...(origin!==undefined?{origin}:{}),...(site!==undefined?{'sec-fetch-site':site}:{})},socket:{encrypted}});
const prod={production:true,siteUrl:'https://shop.example'};
assert(allowed(req('GET','https://evil.example','cross-site'),'/api/products',prod));
assert(allowed(req('POST','https://shop.example','same-origin'),'/api/orders',prod));
assert(allowed(req('POST','https://shop.example','same-origin','internal.proxy'),'/api/orders',prod));
assert(!allowed(req('POST','https://evil.example','cross-site'),'/api/orders',prod));
assert(!allowed(req('POST','https://sub.shop.example','same-site'),'/api/orders',prod));
assert(!allowed(req('POST',undefined,'same-site'),'/api/orders',prod));
assert(!allowed(req('POST',undefined,'cross-site'),'/api/orders',prod));
assert(!allowed(req('POST','null','cross-site'),'/api/orders',prod));
assert(!allowed(req('POST','http://shop.example','same-origin'),'/api/orders',prod));
assert(!allowed(req('POST','https://shop.example.evil.test','same-site'),'/api/orders',prod));
assert(!allowed(req('POST','https://user@shop.example','same-origin'),'/api/orders',prod));
assert(!allowed(req('POST','https://shop.example/path','same-origin'),'/api/orders',prod));
assert(allowed(req('POST',undefined,undefined),'/api/orders',prod));
assert(allowed(req('OPTIONS','https://evil.example','cross-site'),'/api/orders',prod));
assert(allowed(req('GET','https://bank.example','cross-site'),'/payment/callback',prod));
assert(allowed(req('POST','http://localhost:3000','same-origin','localhost:3000'),'/api/orders',{}));
assert(!allowed(req('POST','http://localhost:3001','same-site','localhost:3000'),'/api/orders',{}));
console.log('PASS browser-origin guard: same-origin, sibling/cross-site, proxy, API clients and bank callback');
